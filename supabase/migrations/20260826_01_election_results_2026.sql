  id             bigserial primary key,
  office_raw     text not null,
  office_type    text not null check (office_type in ('congressional','house','senate','statewide','other')),
  district       text,
  candidate_name text not null,
  party          text not null,
  votes          integer not null,
  pct            numeric(6,3),
  advanced       boolean not null default false,
  election_date  date not null default '2026-08-04'
);
create index if not exists election_results_2026_type_district_idx on public.election_results_2026 (office_type, district);
create index if not exists election_results_2026_party_idx on public.election_results_2026 (party);
alter table public.election_results_2026 enable row level security;
